import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsIn,
  IsISO8601,
  IsNumber,
  IsOptional,
  Matches,
  Max,
  Min,
  ValidateNested,
} from 'class-validator';
import { PaginationQueryDto } from '../../../../common/http/dto/pagination-query.dto';
import {
  type GeoPoint,
  HeartRhythm,
  MedicalEventType,
  SafetyLimits,
  type Vitals,
} from '../../domain/safety';

const EVENT_TYPES = Object.values(MedicalEventType);
const RHYTHMS = Object.values(HeartRhythm);
const CLIENT_EVENT_ID = new RegExp(
  `^[A-Za-z0-9_-]{8,${SafetyLimits.CLIENT_EVENT_ID_MAX_LENGTH}}$`,
);
const FINITE = { allowNaN: false, allowInfinity: false };

export class LocationDto {
  @ApiProperty({ minimum: -90, maximum: 90, example: 36.8065 })
  @IsNumber(FINITE)
  @Min(-90)
  @Max(90)
  latitude!: number;

  @ApiProperty({ minimum: -180, maximum: 180, example: 10.1815 })
  @IsNumber(FINITE)
  @Min(-180)
  @Max(180)
  longitude!: number;

  @ApiPropertyOptional({ minimum: 0, maximum: 100_000, example: 12 })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(100_000)
  accuracyM?: number;
}

/** Physiological bounds: anything outside is a sensor fault, not a reading. */
export class VitalsDto implements Vitals {
  @ApiPropertyOptional({ minimum: 0, maximum: 300 })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(300)
  heartRateBpm?: number;

  @ApiPropertyOptional({ minimum: 0, maximum: 100 })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(100)
  spo2Percent?: number;

  @ApiPropertyOptional({ minimum: 0, maximum: 80 })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(80)
  respiratoryRateBpm?: number;

  @ApiPropertyOptional({ minimum: 0, maximum: 100 })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(100)
  eyeClosurePercent?: number;

  @ApiPropertyOptional({ enum: RHYTHMS })
  @IsOptional()
  @IsIn(RHYTHMS)
  rhythm?: HeartRhythm;
}

/** A detection reported by an in-cabin unit. */
export class DeviceEventDto {
  @ApiProperty({
    description:
      'Idempotency key chosen by the unit (8–64 URL-safe characters). Resending the same id is safe.',
    example: 'evt_01J9ZQ4K2M7P',
  })
  @Matches(CLIENT_EVENT_ID)
  clientEventId!: string;

  @ApiProperty({
    enum: EVENT_TYPES,
    description: 'SOS is the cabin emergency button.',
  })
  @IsIn(EVENT_TYPES)
  type!: MedicalEventType;

  @ApiProperty({
    description:
      'Detection time from the unit clock (ISO 8601). At most 24 h old and 5 min ahead.',
  })
  @IsISO8601({ strict: true })
  detectedAt!: string;

  @ApiPropertyOptional({
    minimum: 0,
    maximum: 1,
    description: 'Detector confidence, 0 to 1.',
  })
  @IsOptional()
  @IsNumber(FINITE)
  @Min(0)
  @Max(1)
  confidence?: number;

  @ApiPropertyOptional({ type: VitalsDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => VitalsDto)
  vitals?: VitalsDto;

  @ApiPropertyOptional({
    type: LocationDto,
    description: 'Attach only for emergencies; never for routine events.',
  })
  @IsOptional()
  @ValidateNested()
  @Type(() => LocationDto)
  location?: LocationDto;
}

/** The driver's manual SOS, sent after the app's cancel window. */
export class SosDto {
  @ApiProperty({
    description: 'Idempotency key generated by the app for this press.',
  })
  @Matches(CLIENT_EVENT_ID)
  clientEventId!: string;

  @ApiPropertyOptional({ type: LocationDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => LocationDto)
  location?: LocationDto;
}

export class ListEventsQueryDto extends PaginationQueryDto {
  @ApiPropertyOptional({ enum: EVENT_TYPES })
  @IsOptional()
  @IsIn(EVENT_TYPES)
  type?: MedicalEventType;
}

export function toGeoPoint(location: LocationDto | undefined): GeoPoint | null {
  return location
    ? {
        latitude: location.latitude,
        longitude: location.longitude,
        accuracyM: location.accuracyM ?? null,
      }
    : null;
}

/** Copies only the declared readings (the DTO instance carries no others). */
export function toVitals(vitals: VitalsDto | undefined): Vitals | null {
  if (!vitals) return null;
  const copy: Vitals = {
    heartRateBpm: vitals.heartRateBpm,
    spo2Percent: vitals.spo2Percent,
    respiratoryRateBpm: vitals.respiratoryRateBpm,
    eyeClosurePercent: vitals.eyeClosurePercent,
    rhythm: vitals.rhythm,
  };
  const present = Object.entries(copy).filter(
    ([, value]) => value !== undefined,
  );
  return present.length ? Object.fromEntries(present) : null;
}
